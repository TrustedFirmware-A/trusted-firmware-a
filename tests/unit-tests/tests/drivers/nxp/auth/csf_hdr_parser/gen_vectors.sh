# Regenerate csf_hdr_vectors.h with the NXP Code Signing Tool (CST,
# https://github.com/nxp-qoriq/cst). A throw-away 2048-bit SRK is generated
# on the fly, so every run produces different but equally valid vectors.
#
# Usage: CST_DIR=<cst checkout> TFA_ROOT=<tf-a checkout> ./gen_vectors.sh
#
# The CST input files shipped in TF-A for chassis 3 are reused, with the
# key paths rewritten to the throw-away key.

set -eu

here="$(cd "$(dirname "$0")" && pwd)"
cst_dir="${CST_DIR:?set CST_DIR to a CST checkout providing gen_keys and create_hdr_*}"
tfa_root="${TFA_ROOT:?set TFA_ROOT to a TF-A checkout}"
parser_dir="$tfa_root/drivers/nxp/auth/csf_hdr_parser"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cd "$work"

# Throw-away image and SRK key pair
printf 'lx2160 csf parser unit test image\n' > image.bin
"$cst_dir/gen_keys" 2048 -k srk.pub -p srk.pri > /dev/null

for input in input_bl2_ch3_2 input_blx_ch3; do
	sed -e "s|^PUB_KEY=.*|PUB_KEY=$work/srk.pub|" \
	    -e "s|^PRI_KEY=.*|PRI_KEY=$work/srk.pri|" \
	    "$parser_dir/$input" > "$input"
done

# ISBC header (SG table form, as produced for BL2 by the pbl target)
"$cst_dir/create_hdr_isbc" --in image.bin --out hdr_isbc input_bl2_ch3_2 > /dev/null

# ESBC header with the image appended at 0xc00 (the pre-tool filters in
# TF-A use CSF_HDR_SZ = 0x3000; the parser does not depend on the offset)
"$cst_dir/create_hdr_esbc" --in image.bin --out hdr_esbc --app_off 0xc00 \
	--app image.bin input_blx_ch3 > /dev/null

python3 - "$here/csf_hdr_vectors.h" <<'EOF'
import hashlib
import struct
import sys

out_path = sys.argv[1]
isbc = open('hdr_isbc', 'rb').read()
esbc_full = open('hdr_esbc', 'rb').read()
img_off = 0xc00
esbc = esbc_full[:img_off]
img = esbc_full[img_off:]

# struct csf_hdr (chassis 3) is 0x50 bytes, struct srk_table 4 + 1024 bytes
hdr_size = 0x50
srk_entry = 4 + 2 * 512
srk_off = struct.unpack_from('<I', isbc, 4)[0]
num_srk = isbc[8]
key_len = struct.unpack_from('<I', isbc, srk_off)[0]
sign_len = struct.unpack_from('<I', isbc, 0x14)[0]
isbc_psign = struct.unpack_from('<I', isbc, 0x10)[0]
esbc_psign = struct.unpack_from('<I', esbc, 0x10)[0]

table = isbc[srk_off:srk_off + num_srk * srk_entry]
assert table == esbc[srk_off:srk_off + num_srk * srk_entry]

srk_tbl_hash = hashlib.sha256(table).digest()
srk_key_hash = hashlib.sha256(table[4:4 + key_len]).digest()
img_hash = hashlib.sha256(esbc[:hdr_size] + table + img).digest()


def array(name, data, per_line=12):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = ', '.join('0x%02x' % b for b in data[i:i + per_line])
        lines.append('\t' + chunk + ',')
    return 'static const uint8_t %s[%d] = {\n%s\n};\n' % (
        name, len(data), '\n'.join(lines))


with open(out_path, 'w') as f:
    f.write('''/*
 * Copyright (c) 2026 Free Mobile - Vincent Jardin
 *
 * SPDX-License-Identifier: BSD-3-Clause
 */

/*
 * Test vectors for the NXP CSF header parser, generated by gen_vectors.sh
 * with the NXP Code Signing Tool (CST) 2.0 and a throw-away 2048-bit SRK.
 * Do not edit by hand. Use gen_vectors.sh
 *
 * The SRK in these vectors is a throw-away 2048-bit development key made
 * for this file: it is not a reference key and must never be used as one.
 *
 * Two CSF headers in the NXP Chassis 3 format (LX2160A family), both
 * signed with the same throw-away single-entry SRK table:
 *  - csf_isbc_hdr: an ISBC header as produced for BL2 by create_hdr_isbc
 *  - csf_esbc_hdr: an ESBC header as produced for the images BL2 loads by
 *    create_hdr_esbc, for csf_esbc_img, which is appended at offset
 *    CSF_ESBC_IMG_OFFSET in the CST output file
 */

#ifndef CSF_HDR_VECTORS_H
#define CSF_HDR_VECTORS_H

#include <stdint.h>

/* Offsets and sizes common to both headers */
#define CSF_VEC_SRK_TBL_OFF\t0x%xU
#define CSF_VEC_NUM_SRK\t\t%dU
#define CSF_VEC_KEY_LEN\t\t%dU
#define CSF_VEC_SIGN_LEN\t%dU
#define CSF_ISBC_PSIGN\t\t0x%xU
#define CSF_ESBC_PSIGN\t\t0x%xU
#define CSF_ESBC_IMG_OFFSET\t0x%xU

''' % (srk_off, num_srk, key_len, sign_len, isbc_psign, esbc_psign, img_off))
    f.write(array('csf_isbc_hdr', isbc) + '\n')
    f.write(array('csf_esbc_hdr', esbc) + '\n')
    f.write(array('csf_esbc_img', img) + '\n')
    f.write('/* SHA-256 of the SRK table (CSF_VEC_NUM_SRK entries), '
            'i.e. the SRKH fuse value */\n')
    f.write(array('csf_vec_srk_tbl_hash', srk_tbl_hash) + '\n')
    f.write('/* SHA-256 of the selected public key (CSF_VEC_KEY_LEN bytes) */\n')
    f.write(array('csf_vec_srk_key_hash', srk_key_hash) + '\n')
    f.write('/* SHA-256 of ESBC header + SRK table + image, '
            'the value CST signed */\n')
    f.write(array('csf_vec_esbc_img_hash', img_hash) + '\n')
    f.write('#endif /* CSF_HDR_VECTORS_H */\n')

print('wrote', out_path)
EOF
